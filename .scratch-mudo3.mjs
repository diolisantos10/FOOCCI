import { chromium } from "playwright-core";
const b = await chromium.launch({ args: ["--autoplay-policy=user-gesture-required"] });
const ctx = await b.newContext({ viewport:{width:1280,height:900} });
const p = await ctx.newPage();
p.on("request", r => { const u=r.url(); if (u.includes("/api/orders")) console.log("[req]", u); });
await p.goto("http://localhost:3000/login",{waitUntil:"networkidle"});
await p.fill('input[type="email"]',"owner@pizzaria-demo.com");
await p.fill('input[type="password"]',"demo1234");
await p.locator("form button[type=submit]").click();
await p.waitForURL(u=>!u.pathname.includes("/login"),{timeout:60000}).catch(()=>{});
await p.goto("http://localhost:3000/dashboard?painel=1",{waitUntil:"networkidle"});
await p.waitForTimeout(14000);
console.log("url:", p.url());
console.log("diag:", await p.evaluate(() => localStorage.getItem("foocci_order_alert_diag")));
console.log("chaves:", await p.evaluate(() => Object.keys(localStorage)));
await b.close();
